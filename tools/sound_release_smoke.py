"""Release Sound/privacy checks. Clears only mz music data on a disposable emulator."""
import argparse,json,re,time
from pathlib import Path
from emulator_ui import Emulator
parser=argparse.ArgumentParser()
parser.add_argument('--adb',required=True); parser.add_argument('--serial',required=True)
args=parser.parse_args(); e=Emulator(args.adb,args.serial)
root=Path(__file__).resolve().parents[1]
version=re.search(r'versionName = "([^"]+)"',(root/'app/build.gradle.kts').read_text())[1]
out=root/'validation'/version; out.mkdir(parents=True,exist_ok=True)
results=[]
def record(name):
    results.append({'check':name,'result':'PASS'})
    (out/'sound-release-results.json').write_text(json.dumps(results,indent=2)+'\n')
    print('PASS',name,flush=True)
def shot(name): (out/name).write_bytes(e.run('exec-out','screencap','-p',binary=True))

e.run('install','-r',str(root/f'dist/mz-music-{version}-release.apk'))
e.run('shell','pm','clear','local.music')
e.run('shell','pm','grant','local.music','android.permission.READ_MEDIA_AUDIO')
e.run('logcat','-c')
e.run('shell','mkdir','-p','/sdcard/Music/LocalMusicQA')
fixtures=list((root/'.tooling/fixtures').iterdir())+[root/'.tooling/security-review/05 - Boost tag test.flac']
for file in fixtures:
    if file.suffix not in ('.wav','.mp3','.m4a','.flac'): continue
    target='/sdcard/Music/LocalMusicQA/'+file.name
    e.run('push',str(file),target)
    e.run('shell','am','broadcast','-a','android.intent.action.MEDIA_SCANNER_SCAN_FILE','-d',"'file://"+target+"'")
e.run('shell','input','keyevent','KEYCODE_WAKEUP'); e.run('shell','wm','dismiss-keyguard')
e.run('shell','am','start','-n','local.music/.MainActivity'); time.sleep(1)
e.tap('Sound'); e.contains('All app effects bypassed'); e.find('Flat')
record('Release starts in Original with Flat settings')
e.tap('Flat'); e.tap('Headphones'); e.tap('Tuned')
e.click(e.find('31 Hz gain'),.75); e.tap('Save changes'); e.find('Headphones')
e.restart(); e.tap('Sound'); e.find('Headphones'); e.contains('+6.5 dB')
record('Edited built-in preset survives process recreation')
e.tap('Save as…'); e.name('Review'); e.tap('Rename'); e.name('Personal','Review')
e.click(e.find('62 Hz gain'),.35)
e.contains('-4.0 dB')
e.restart(); e.tap('Sound'); e.find('Personal (edited)'); e.contains('-4.0 dB')
record('Custom preset names and unsaved changes persist')
e.tap('Original'); e.find('Switch to Original?'); e.tap('Cancel'); e.contains('Limiter on')
e.tap('Original'); e.tap('Switch to Original'); e.contains('All app effects bypassed')
e.find('Personal (edited)'); e.tap('Tuned')
record('Original requires confirmation and preserves settings')
e.tap('Delete'); e.tap('Delete'); e.find('Custom (unsaved)')
e.tap('Reset to Flat'); e.find('Flat')
record('Deleting a preset retains edits and Reset restores Flat')
e.tap('Back from Sound'); e.tap('02 - MP3 test'); e.session({3},'02 - MP3 test')
e.tap('Sound'); e.click(e.reach('Track leveling')); e.contains('Track gain -6.0 dB')
record('MP3 ReplayGain works in the release audio pipeline')
e.tap('Album leveling'); e.contains('Album gain -9.0 dB'); e.tap('Track leveling')
record('Album gain is distinct from Track gain')
e.media('next'); e.session({3},'03 - M4A test'); e.contains('Track gain -3.0 dB')
e.media('next'); e.session({3},'04 - FLAC test'); e.contains('Track gain -12.0 dB')
record('M4A and FLAC tags replace the preceding track gain')
e.media('next'); e.session({3},'05 - Boost tag test'); e.contains('Tag +30.0 dB; boost limited')
record('Positive ReplayGain is capped to +6 dB by default')
e.tap('Limit ReplayGain boost'); e.find('Allow larger tag boosts?'); e.tap('Cancel')
e.contains('boost limited'); e.tap('Limit ReplayGain boost'); e.tap('Allow larger boosts')
e.contains('Track gain +30.0 dB'); e.tap('Limit ReplayGain boost'); e.contains('boost limited')
record('Disabling the boost cap requires explicit confirmation')
for _ in range(5): e.media('previous')
e.session({3},'01 - WAV test'); e.contains('No track leveling data')
record('Untagged audio does not inherit another track gain')
e.media('pause'); e.session({2})
e.click(e.reach('Private listening'))
session=e.session({2},'Private listening')
assert '01 - WAV test' not in session and '02 - MP3 test' not in session
windows=e.run('shell','dumpsys','window','windows')
(out/'private-window.txt').write_text(windows)
assert 'SECURE' in windows
shot('private-listening.png')
record('Private listening redacts session metadata and enables secure windows')
e.restart(); e.tap('Sound'); e.reach('Private listening')
assert e.checked('Private listening')
e.session({0,2},'Private listening')
record('Privacy preference survives restart before paused queue publication')
e.tap('Clear listening data'); e.tap('Cancel'); e.session({0,2},'Private listening')
e.tap('Clear listening data'); e.tap('Clear queue')
e.reach('Queue and saved position cleared. Music files are unchanged.')
record('Clear listening data waits for durable erasure and preserves music files')
e.restart(); e.tap('Sound'); e.reach('Private listening')
assert 'size=0' in e.session({0})
e.tap('Private listening'); e.contains('Privacy & saved data')
shot('privacy-controls.png')
e.tap('Back from Sound'); e.find('02 - MP3 test')
record('Cleared queue stays empty after restart; music remains in the library')
crashes=e.run('logcat','-d','-s','AndroidRuntime:E'); (out/'release-sound-crashes.txt').write_text(crashes)
assert 'Process: local.music' not in crashes
record('No app runtime crashes during release Sound/privacy checks')
print('All release Sound/privacy checks passed.',flush=True)
